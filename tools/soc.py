#!/usr/bin/env python3
"""Build settings for one target: a SoC described by a target directory, Spike, or this machine.

usage: tools/soc.py SOC OUTDIR
  SOC = a target directory holding target.json (below)
      | spike:MARCH/MABI (e.g. spike:rv64imafdc_zicsr_zifencei/lp64d)
      | host (this machine's CPU and C compiler: the same program built with gcc and run directly)

target.json (written by whatever describes the SoC; paths relative to the directory or absolute):
  {"name": "my_soc", "march": "rv64imac_zicsr_zifencei", "mabi": "lp64",
   "memory": {"base": "0x80000000", "size": "0x200000"},     main memory the program links into
   "clock_hz": 50000000, "bus_width": 64,
   "include": ["inc"],            headers; one of them, soc.h, defines UART0_BASE (the console: a uart_v3)
   "sources": ["board_init.c"],   extra C sources linked into every program
   "board_init": true}            sources define board_init(), called before main

Writes OUTDIR/soc.mk (MARCH, MABI, include path, console, extra sources) and OUTDIR/link.ld (from
runtime/shakti/link.ld.in with the target's memory).  Nothing about a SoC is written by hand in this repository.
Programs are only built for a target directory: running them is the job of the tool that describes the SoC.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPIKE_MEM = (0x80000000, 0x10000000)          # Spike's default DRAM base; 256 MiB used


def dir_target(d):
    p = os.path.join(d, "target.json")
    if not os.path.isfile(p):
        sys.exit(f"{d}: no target.json (a target directory describes the SoC: tools/soc.py --help)")
    t = json.load(open(p))
    try:
        mem = t["memory"]
        num = (lambda v: int(v, 0) if isinstance(v, str) else int(v))
        path = (lambda f: f if os.path.isabs(f) else os.path.join(d, f))
        return {"clock_hz": int(t.get("clock_hz") or 50000000), "name": t["name"], "march": t["march"],
                "mabi": t["mabi"], "inc": [path(i) for i in t.get("include") or []], "console": "UART",
                "base": num(mem["base"]), "size": num(mem["size"]),
                "extra": [path(f) for f in t.get("sources") or []], "bus_width": int(t.get("bus_width") or 64),
                "board_init": bool(t.get("board_init"))}
    except (KeyError, TypeError, ValueError) as e:
        sys.exit(f"{p}: {type(e).__name__} {e} (needs name, march, mabi, memory.base, memory.size)")


def spike_target(spec):
    march, mabi = spec.split("/")
    return {"clock_hz": 1000000000, "name": f"spike-{march.split('_')[0]}", "march": march, "mabi": mabi, "inc": [], "console": "HTIF",
            "base": SPIKE_MEM[0], "size": SPIKE_MEM[1], "extra": [], "bus_width": 64, "board_init": False}


def host_target():
    return {"clock_hz": 1000000000, "name": "host", "march": "", "mabi": "", "inc": [], "console": "HOST",
            "base": 0, "size": 0, "extra": [], "bus_width": 64, "board_init": False}


def write(path, text):
    """Write a file only when its text changes (the apps' objects depend on it)."""
    if os.path.exists(path) and open(path).read() == text:
        return
    tmp = f"{path}.{os.getpid()}"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__)
    soc, out = argv
    t = spike_target(soc[6:]) if soc.startswith("spike:") else host_target() if soc == "host" else \
        dir_target(os.path.abspath(soc))
    os.makedirs(out, exist_ok=True)
    tpl = open(os.path.join(ROOT, "runtime", "shakti", "link.ld.in")).read()
    write(os.path.join(out, "link.ld"),
          tpl.replace("@MEMORY_BASE@", f"0x{t['base']:08X}").replace("@MEMORY_SIZE@", f"0x{t['size']:X}"))
    lines = [f"# generated by tools/soc.py from {soc}",
             f"SOC_NAME := {t['name']}", f"MARCH := {t['march']}", f"MABI := {t['mabi']}",
             f"SOC_INC := {' '.join('-I' + i for i in t['inc'])}", f"CONSOLE := {t['console']}",
             f"SOC_SRCS := {' '.join(t['extra'])}", f"SOC_BOARD_INIT := {1 if t['board_init'] else ''}", f"BUS_WIDTH := {t['bus_width']}",
             f"CLOCK_HZ := {t['clock_hz']}", f"HOST := {1 if soc == 'host' else ''}", f"MEMORY_BASE := 0x{t['base']:08X}", f"MEMORY_SIZE := 0x{t['size']:X}", ""]
    write(os.path.join(out, "soc.mk"), "\n".join(lines))
    print(f"{t['name']}: {t['march']}/{t['mabi']}, memory 0x{t['base']:08X} + 0x{t['size']:X}, console {t['console']}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
